"""
This function loads the parameters from the configuration workbook (config/*.xlsx) and stores them in a nested
dictionary para[sheet][category][variable] (or para[sheet][variable] if the category is empty). Only the columns
'Category', 'Variable' and 'Value' are read, all other columns are documentation. Empty values are set to 0 and
integral numbers are stored as int, so that they can be used as counters and indices.
Inputs:     1) fileName:    name of the config file relative to config/ without extension, e.g. "default/default"
            2) path:        includes all path variables
Outputs:    1) para:        nested dictionary with all parameters
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
from os.path import join as pjoin
import pandas as pd
import numpy as np
import sys


#######################################################################################################################
# Additional Functions
#######################################################################################################################
def _convValue(value):
    # Empty
    if value is None or (isinstance(value, float) and np.isnan(value)):
        return 0

    # Numeric
    if isinstance(value, (int, float, np.integer, np.floating)):
        if float(value).is_integer():
            return int(value)
        return float(value)

    # String (numbers stored as text are converted)
    try:
        val = float(str(value).replace(',', '.'))
        return int(val) if val.is_integer() else val
    except ValueError:
        return str(value)


#######################################################################################################################
# Main Function
#######################################################################################################################
def loadPara(fileName, path):
    ###################################################################################################################
    # MSG IN
    ###################################################################################################################
    print("------------------------------------------")
    print("START: Loading Config Parameters")
    print("------------------------------------------")

    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    # ==============================================================================
    # Parameters
    # ==============================================================================
    name = str(fileName).replace('\\', '/').strip('/')
    fullName = pjoin(path['config'], *name.split('/')) + '.xlsx'
    sheets = ['Exp', 'Dat', 'Mdl', 'Par']

    # ==============================================================================
    # Variables
    # ==============================================================================
    para = {}

    ###################################################################################################################
    # Loading Data
    ###################################################################################################################
    try:
        raw = pd.read_excel(fullName, sheet_name=None)
    except Exception as e:
        sys.exit('ERROR: Configuration could not be loaded (' + fullName + '): ' + str(e))

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    for sheet in sheets:
        # ==============================================================================
        # Check Sheet
        # ==============================================================================
        if sheet not in raw:
            sys.exit('ERROR: Sheet "' + sheet + '" not found in ' + fullName)
        df = raw[sheet]
        if not all(c in df.columns for c in ['Category', 'Variable', 'Value']):
            sys.exit('ERROR: Sheet "' + sheet + '" must contain the columns Category, Variable and Value')

        # ==============================================================================
        # Rows
        # ==============================================================================
        para[sheet] = {}
        for _, row in df.iterrows():
            var = row['Variable']
            if not isinstance(var, str):
                continue
            cat = row['Category']
            val = _convValue(row['Value'])

            # No Category
            if not isinstance(cat, str):
                para[sheet][var] = val

            # Category
            else:
                para[sheet].setdefault(cat, {})[var] = val

    ###################################################################################################################
    # MSG Out
    ###################################################################################################################
    print("DONE: Loading Config Parameters (" + name + ")")
    print("")

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return para


