import numpy as np
from scipy.signal import lfilter


#######################################################################################################################
# Additional Functions
#######################################################################################################################
def _ewma(x, a):
    zi = ((1 - a) * x[0])[None, :]
    return lfilter([a], [1, -(1 - a)], x, axis=0, zi=zi)[0]


def _ewms(x, a, legacy):
    mu = _ewma(x, a)
    muPrev = np.vstack([x[0:1], mu[:-1]])
    d = (x - muPrev) ** 2
    d[0] = 0
    if legacy == 1:
        var = lfilter([a], [1, -(1 - a)], d, axis=0)
    else:
        var = lfilter([(1 - a) * a], [1, -(1 - a)], d, axis=0)
    return np.sqrt(np.maximum(var, 0))


#######################################################################################################################
# Main Function
#######################################################################################################################
def calcFeat(X, EWMA, EWMS, ids=None, legacy=0):
    ###################################################################################################################
    # MSG IN
    ###################################################################################################################
    print("START: Calculation Features")

    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    X = np.atleast_2d(np.asarray(X, dtype=float).T).T
    if ids is None or legacy == 1:
        ids = np.ones(X.shape[0])
    ids = np.asarray(ids)
    feats = [X]

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    for spans, fnc in ((EWMA, 'a'), (EWMS, 's')):
        for s in [s for s in np.atleast_1d(spans) if s > 0]:
            a = 2.0 / (s + 1)
            res = np.zeros_like(X)
            for i in np.unique(ids):
                m = ids == i
                res[m] = _ewma(X[m], a) if fnc == 'a' else _ewms(X[m], a, legacy)
            feats.append(res)

    ###################################################################################################################
    # MSG Out
    ###################################################################################################################
    print("DONE: Calculation Features")

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return np.hstack(feats)


