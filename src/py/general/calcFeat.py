"""
This function extends the input features with exponentially weighted moving averages (EWMA) and standard deviations
(EWMS) for every span s in EWMA/EWMS. With α = 2/(s+1):

    μ(t)  = α·x(t) + (1-α)·μ(t-1)                               μ(0) = x(0)
    σ²(t) = (1-α)·(σ²(t-1) + α·(x(t) - μ(t-1))²)                σ²(0) = 0

The recursion restarts at the beginning of every profile (id), so that no information is shared between profiles.
Inputs:     1) X:       input features (Nt x F)
            2) EWMA:    list of spans for the moving average (samples)
            3) EWMS:    list of spans for the moving standard deviation (samples)
            4) ids:     profile id per sample (Nt), if None one profile is assumed
            5) legacy:  (0): corrected behaviour, (1): MATLAB behaviour
Outputs:    1) Xout:    extended features (Nt x F·(1 + len(EWMA) + len(EWMS)))

V1.0: 07.11.2026, Pascal Schirmer
- Python port of calcFeat.m, vectorised with lfilter, restart per profile and standard EW variance
  (legacy: σ²(t) = α·(x(t)-μ(t-1))² + (1-α)·σ²(t-1), no restart, F-G1)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
