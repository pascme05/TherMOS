"""
This function returns the index of the spatial node that is closest to a given position. The position is measured
relative to the minimum of the geometry, i.e. (0, 0, 0) is the corner of the bounding box, as in the plotting
functions. In legacy mode the position is an absolute coordinate as in concatData.m/dimData.m (F-D12).
Inputs:     1) geo:     node coordinates (N x 2 or N x 3) (m)
            2) pos:     position (x, y) or (x, y, z) (m)
            3) legacy:  (0): relative position, (1): absolute position
Outputs:    1) idx:     index of the closest node (L1 distance as in MATLAB)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
import numpy as np


#######################################################################################################################
# Main Function
#######################################################################################################################
def findNode(geo, pos, legacy=0):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    geo = np.asarray(geo, dtype=float)
    pos = np.asarray(pos, dtype=float).ravel()
    dim = len(pos)

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    ref = geo[:, 0:dim]
    if legacy == 0:
        ref = ref - ref.min(axis=0)
    idx = int(np.argmin(np.sum(np.abs(ref - pos), axis=1)))

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return idx


