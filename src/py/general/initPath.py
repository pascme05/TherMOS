"""
This function initialises all path variables of the toolkit. The base path is the folder of the start script, i.e.
the repository root. The folders config/, data/, mdl/, setup/, results/ and docu/ are shared between the MATLAB and
the Python version.
Inputs:     1) base:    repository root (str), if empty the current working directory is used
Outputs:    1) path:    dictionary with all paths (config, data, mdl, setup, src, results, docu)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
from os.path import join as pjoin
import os


#######################################################################################################################
# Main Function
#######################################################################################################################
def initPath(base=''):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    if base == '':
        base = os.getcwd()

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    path = {
        'base': base,
        'config': pjoin(base, 'config'),
        'data': pjoin(base, 'data'),
        'mdl': pjoin(base, 'mdl'),
        'setup': pjoin(base, 'setup'),
        'src': pjoin(base, 'src', 'py'),
        'results': pjoin(base, 'results'),
        'docu': pjoin(base, 'docu'),
    }

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return path


