"""
This function saves the data, the setup and the parameters of a simulation to results/<name>/ as pickle files with
a time stamp in the file name.
Inputs:     1) data:    all data including predictions
            2) setup:   includes all simulation variables
            3) para:    all simulation parameters
            4) path:    includes all path variables
            5) tag:     model tag added to the file names (e.g. 'ss')
Outputs:    None

V1.0: 07.11.2026, Pascal Schirmer
- Python port of saving.m, setup and parameters are written to the files with the matching name (F-M1)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
from os.path import join as pjoin
import datetime
import os
import pickle


#######################################################################################################################
# Main Function
#######################################################################################################################
def saving(data, setup, para, path, tag=''):
    ###################################################################################################################
    # MSG IN
    ###################################################################################################################
    print("INFO: Saving results")

    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    time = datetime.datetime.now().strftime('%Y-%m-%d_%H-%M-%S')
    name = setup['name'] + ('_' + tag if tag else '') + '_' + time
    folder = pjoin(path['results'], setup['name'])
    os.makedirs(folder, exist_ok=True)

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    for (fName, obj) in (('result_data_', data), ('result_setup_', setup), ('result_para_', para)):
        with open(pjoin(folder, fName + name + '.pkl'), 'wb') as f:
            pickle.dump(obj, f)

    ###################################################################################################################
    # MSG Out
    ###################################################################################################################
    print("INFO: Results saved to " + folder)


