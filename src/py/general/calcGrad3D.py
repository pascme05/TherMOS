"""
This function calculates the temperature gradient and the heat flux of a 3D temperature field T(x,y,z,t) on the
regular grid x = 0:dx:Lx, y = 0:dy:Ly, z = 0:dz:Lz:

    |∇T| = sqrt((∂T/∂x)² + (∂T/∂y)² + (∂T/∂z)²)    magnitude of the temperature gradient (K/m)
    |q|  = k · |∇T|                                 magnitude of the heat flux (W/m²)

Inputs:     1) data:    data including y (Nt x N) and Data (geo, dx, dy, dz, Lx, Ly, Lz, k)
            2) inp:     (-1) last sample only, (1) all samples
            3) legacy:  (0): corrected behaviour, (1): MATLAB behaviour
Outputs:    1) out:     data including qk = |∇T| (K/m) and q = k·|∇T| (W/m²), shape (Ny x Nx x Nz) for inp=-1 and
                        (Nt x Ny x Nx x Nz) otherwise

V1.0: 07.11.2026, Pascal Schirmer
- Python port of calcGrad3D.m, magnitude instead of the sum of the components and correct spacings (F-G2)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================
from src.py.general.map3D import map3D

# ==============================================================================
# External
# ==============================================================================
import numpy as np


#######################################################################################################################
# Main Function
#######################################################################################################################
def calcGrad3D(data, inp=-1, legacy=0):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    D = data['Data']
    dx, dy, dz = D['dx'], D['dy'], D['dz']
    x = np.arange(0, D['Lx'] + dx * 1e-6, dx)
    y = np.arange(0, D['Ly'] + dy * 1e-6, dy)
    z = np.arange(0, D['Lz'] + dz * 1e-6, dz)
    g = D['geo'] - D['geo'].min(axis=0)

    ###################################################################################################################
    # Pre-Processing
    ###################################################################################################################
    k = map3D(D['k'], g[:, 0], g[:, 1], g[:, 2], x, y, z, 1)[0]
    yT = np.asarray(data['y'])
    if inp == -1:
        yT = yT[-1:, :]
    T = map3D(yT, g[:, 0], g[:, 1], g[:, 2], x, y, z, 1)

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    if legacy == 1:
        gA, gB, gC = np.gradient(T, dx, dy, dz, axis=(1, 2, 3))
        qk = -(gA + gB + gC)
    else:
        dTdy, dTdx, dTdz = np.gradient(T, dy, dx, dz, axis=(1, 2, 3))
        qk = np.sqrt(dTdx ** 2 + dTdy ** 2 + dTdz ** 2)
    q = k[None] * qk

    ###################################################################################################################
    # Post-Processing
    ###################################################################################################################
    if inp == -1:
        q, qk = q[0], qk[0]

    ###################################################################################################################
    # Return
    ###################################################################################################################
    out = dict(data)
    out['q'] = q
    out['qk'] = qk
    return out


