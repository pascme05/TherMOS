"""
This function calculates the temperature dependent scaling factor of the losses. The losses consist of a temperature
independent contact resistance (Rcon) and a conduction resistance (Rohm) that changes linearly with temperature:

    θ(T) = (Rcon + Rohm·(1 + Rslope·(T - Tref))) / (Rcon + Rohm)

with T the temperature (°C), Tref the reference temperature at which the losses are given (°C) and Rslope the
relative resistance change (1/K), e.g. 0.00393 1/K for copper. At T = Tref the factor is one. If Rohm is zero the
losses are temperature independent (θ = 1).
Inputs:     1) T:       temperature (°C)
            2) para:    all simulation parameters (para['Par']['loss'])
            3) legacy:  (0): formula above, (1): MATLAB formula (Rcon + Rohm·Rslope·(T-Tref))/(Rcon+Rohm+eps) (F-D1)
Outputs:    1) theta:   loss scaling factor (p.u.)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
import numpy as np


#######################################################################################################################
# Main Function
#######################################################################################################################
def calcTheta(T, para, legacy=0):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    loss = para['Par']['loss']
    Rcon = loss['Rcon']
    Rohm = loss['Rohm']
    Rslope = loss['Rslope']
    Tref = loss['Tref']
    eps = para['Par']['gen']['eps']

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    if Rohm == 0:
        theta = np.ones_like(np.asarray(T, dtype=float))
    elif legacy == 1:
        theta = (Rcon + Rohm * Rslope * (np.asarray(T) - Tref)) / (Rcon + Rohm + eps)
    else:
        theta = (Rcon + Rohm * (1 + Rslope * (np.asarray(T) - Tref))) / (Rcon + Rohm)

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return theta


