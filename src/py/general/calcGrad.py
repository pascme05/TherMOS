"""
This function calculates the temperature gradient and the heat flux of a 2D temperature field T(x,y,t) on the
regular grid x = 0:dx:Lx, y = 0:dy:Ly:

    |∇T| = sqrt((∂T/∂x)² + (∂T/∂y)²)       magnitude of the temperature gradient (K/m)
    |q|  = k · |∇T|                         magnitude of the heat flux (Fourier's law) (W/m²)

with k the thermal conductivity (W/mK). The derivatives are central differences (one-sided at the edges).
Inputs:     1) data:    data including y (Nt x N) and Data (geo, dx, dy, Lx, Ly, k)
            2) legacy:  (0): corrected behaviour, (1): MATLAB behaviour
Outputs:    1) out:     data including qk = |∇T| (Nt x Ny x Nx) (K/m) and q = k·|∇T| (W/m²)

V1.0: 07.11.2026, Pascal Schirmer
- Python port of calcGrad.m. MATLAB used gradient(T, dy, dx) (spacings swapped) and the sum of the components
  -(∂T/∂x + ∂T/∂y) instead of the magnitude; this is kept for legacy=1 (F-G2)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================
from src.py.general.map2D import map2D

# ==============================================================================
# External
# ==============================================================================
import numpy as np


#######################################################################################################################
# Main Function
#######################################################################################################################
def calcGrad(data, legacy=0):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    D = data['Data']
    dx, dy = D['dx'], D['dy']
    x = np.arange(0, D['Lx'] + dx * 1e-6, dx)
    y = np.arange(0, D['Ly'] + dy * 1e-6, dy)
    xInp = D['geo'][:, 0] - D['geo'][:, 0].min()
    yInp = D['geo'][:, 1] - D['geo'][:, 1].min()

    ###################################################################################################################
    # Pre-Processing
    ###################################################################################################################
    k = map2D(D['k'], xInp, yInp, x, y, 1)[0]
    T = map2D(data['y'], xInp, yInp, x, y, 1)

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    if legacy == 1:
        gA, gB = np.gradient(T, dx, dy, axis=(1, 2))
        qk = -(gA + gB)
    else:
        dTdy, dTdx = np.gradient(T, dy, dx, axis=(1, 2))
        qk = np.sqrt(dTdx ** 2 + dTdy ** 2)
    q = k[None, :, :] * qk

    ###################################################################################################################
    # Return
    ###################################################################################################################
    out = dict(data)
    out['q'] = q
    out['qk'] = qk
    return out


