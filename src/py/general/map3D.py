"""
This function maps a snapshot quantity at scattered points (e.g. FE nodes) to a regular 3D grid.
Inputs:     1) Tin:     snapshot matrix (Nt x N) or vector (N)
            2) xInp:    x coordinates of the scattered points (N) (m)
            3) yInp:    y coordinates of the scattered points (N) (m)
            4) zInp:    z coordinates of the scattered points (N) (m)
            5) xOut:    x grid vector (Nx) (m)
            6) yOut:    y grid vector (Ny) (m)
            7) zOut:    z grid vector (Nz) (m)
            8) inter:   (1) nearest, (2) linear, (3) natural
Outputs:    1) Tout:    field on the grid (Nt x Ny x Nx x Nz)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================
from src.py.numeric.calcInterpMat import calcInterpMat

# ==============================================================================
# External
# ==============================================================================
import numpy as np


#######################################################################################################################
# Main Function
#######################################################################################################################
def map3D(Tin, xInp, yInp, zInp, xOut, yOut, zOut, inter=1):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    Tin = np.atleast_2d(np.asarray(Tin, dtype=float))
    Xq, Yq, Zq = np.meshgrid(xOut, yOut, zOut)

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    M = calcInterpMat(np.column_stack([xInp, yInp, zInp]),
                      np.column_stack([Xq.ravel(), Yq.ravel(), Zq.ravel()]), inter)
    Tout = np.asarray((M @ Tin.T).T)

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return Tout.reshape(Tin.shape[0], len(yOut), len(xOut), len(zOut))


