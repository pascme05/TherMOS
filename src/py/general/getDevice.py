"""
This function returns the compute device of the neural networks (DL and PI mode) from para['Mdl']['gen']['dev']:
(0) CPU, (1) GPU (CUDA). If a GPU is requested but PyTorch has no CUDA support or no GPU is found, the CPU is used and
a warning is printed (install a CUDA build of PyTorch, see https://pytorch.org/get-started/locally/).
Inputs:     1) para:    all simulation parameters
            2) verbose: (0): no message, (1): message with the selected device
Outputs:    1) dev:     torch.device
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
import torch


#######################################################################################################################
# Main Function
#######################################################################################################################
def getDevice(para, verbose=1):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    sel = int(para.get('Mdl', {}).get('gen', {}).get('dev', 0) or 0)

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    if sel == 1 and torch.cuda.is_available():
        dev = torch.device('cuda')
        if verbose:
            print("INFO: Device GPU (%s)" % torch.cuda.get_device_name(0))
    else:
        dev = torch.device('cpu')
        if sel == 1:
            print("WARN: GPU requested, but PyTorch %s has no CUDA support or no GPU was found, the CPU is used"
                  % torch.__version__)
        elif verbose:
            print("INFO: Device CPU")

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return dev


