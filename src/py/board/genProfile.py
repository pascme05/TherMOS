"""
This function generates the loss profile P(t) of one chip:
    'step':     P for t ≥ tOn, 0 before
    'pulse':    P during the first duty·period of every period (from tOn)
    'sine':     P·(1 + amp·sin(2π t/period))/(1 + amp), i.e. between P(1 − amp)/(1 + amp) and P
    'random':   piece-wise constant random levels between 0 and P, new level every hold seconds (training data that
                excite all chips independently)
Inputs:     1) kind:    profile type ('step', 'pulse', 'sine', 'random')
            2) P:       loss level (W)
            3) t:       time vector (Nt) (sec)
            4) par:     {'tOn', 'period', 'duty', 'amp', 'hold'} (sec, p.u.)
            5) seed:    random seed ('random')
Outputs:    1) p:       losses (Nt) (W)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
import numpy as np


#######################################################################################################################
# Main Function
#######################################################################################################################
def genProfile(kind, P, t, par=None, seed=42):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    par = par or {}
    t = np.asarray(t, dtype=float)
    tOn = float(par.get('tOn', 0.0))
    period = max(float(par.get('period', t[-1] / 4 if len(t) > 1 else 1.0)), 1e-9)

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    if kind == 'pulse':
        p = np.where((t >= tOn) & (((t - tOn) % period) < float(par.get('duty', 0.5)) * period), P, 0.0)
    elif kind == 'sine':
        a = float(par.get('amp', 0.5))
        p = P * (1 + a * np.sin(2 * np.pi * t / period)) / (1 + a)
    elif kind == 'random':
        rng = np.random.default_rng(seed)
        hold = max(float(par.get('hold', period / 2)), 1e-9)
        lev = rng.uniform(0, 1, int(np.ceil((t[-1] + 1e-9) / hold)) + 1)
        p = P * lev[np.minimum((t // hold).astype(int), len(lev) - 1)]
    else:
        p = np.where(t >= tOn, P, 0.0)

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return p


