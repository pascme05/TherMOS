"""
This function turns a mission profile (a sequence of operating segments) into the loss profiles of the chips. Every
segment has a duration, a ramp time and the losses of the chips:

    segment | duration [s] | ramp [s] | scale [-] | <chip name> [W] | <chip name> [W] | ...

The loss of a chip in a segment is the value of its column (W) if the column exists and is not empty, otherwise
scale · P_nominal of the chip (the loss entered in the chip table). At the start of a segment the losses change
linearly from the previous level within the ramp time (0: step). The sequence is repeated 'repeat' times.

    P_i(t) = P_i,k-1 + (P_i,k - P_i,k-1)·min((t - t_k)/t_ramp,k, 1)       for t_k ≤ t < t_k + duration_k

Inputs:     1) seq:     sequence, list of dicts {'segment', 'duration [s]', 'ramp [s]', 'scale [-]', <chip> [W]}
            2) chips:   chips [{'name', 'P'}] (order of the output columns)
            3) t:       time vector (Nt) (sec)
            4) repeat:  number of repetitions of the sequence
Outputs:    1) P:       losses (Nt x nChips) (W)
            2) tEnd:    length of the repeated sequence (sec)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
import numpy as np


#######################################################################################################################
# Additional Functions
#######################################################################################################################
def _num(v, default):
    try:
        v = float(v)
        return default if np.isnan(v) else v
    except (TypeError, ValueError):
        return default


#######################################################################################################################
# Main Function
#######################################################################################################################
def genMission(seq, chips, t, repeat=1):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    # ==============================================================================
    # Parameters
    # ==============================================================================
    t = np.asarray(t, dtype=float)
    seq = [s for s in seq if _num(s.get('duration [s]'), 0.0) > 0] * max(int(repeat), 1)

    # ==============================================================================
    # Variables
    # ==============================================================================
    P = np.zeros((len(t), len(chips)))
    if not seq:
        return [P, 0.0]

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    # ==============================================================================
    # Levels per Segment
    # ==============================================================================
    lvl = np.zeros((len(seq), len(chips)))
    for k, s in enumerate(seq):
        sc = _num(s.get('scale [-]'), 1.0)
        for i, c in enumerate(chips):
            lvl[k, i] = _num(s.get(f"{c['name']} [W]"), sc * float(c['P']))
    dur = np.array([_num(s.get('duration [s]'), 0.0) for s in seq])
    ramp = np.array([max(_num(s.get('ramp [s]'), 0.0), 0.0) for s in seq])
    t0 = np.concatenate([[0.0], np.cumsum(dur)])

    # ==============================================================================
    # Profiles
    # ==============================================================================
    k = np.clip(np.searchsorted(t0, t, side='right') - 1, 0, len(seq) - 1)
    prev = np.vstack([lvl[0:1], lvl[:-1]])[k]
    frac = np.where(ramp[k] > 0, np.clip((t - t0[k]) / np.maximum(ramp[k], 1e-12), 0.0, 1.0), 1.0)
    P = prev + (lvl[k] - prev) * frac[:, None]

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return [np.maximum(P, 0.0), float(t0[-1])]


