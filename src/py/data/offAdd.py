"""
This function adds the offset that was removed by offRemove back to the output data (concatenated and per profile).
Inputs:     1) data:    data of one split including 'off' and 'off2'
            2) para:    all simulation parameters
Outputs:    1) out:     data with offset
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
import numpy as np


#######################################################################################################################
# Main Function
#######################################################################################################################
def offAdd(data, para):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    out = dict(data)
    init = para['Exp']['gen']['init']

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    out['y'] = np.asarray(data['y']) + data['off']
    if 'y2' in data and 'off2' in data and len(data['y2']) == len(data['off2']):
        out['y2'] = [data['y2'][i] + data['off2'][i] for i in range(0, len(data['y2']))]

    ###################################################################################################################
    # MSG Out
    ###################################################################################################################
    if init == 2:
        print("INFO: Initial values added")
    elif init == 3:
        print("INFO: Reference signal added")
    else:
        print("INFO: Output data unchanged")

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return out


