"""
This function updates the training and validation losses with respect to the measured temperature (forward
correction, para['Par']['loss']['fw']=1). Input channel i is scaled with θ(T_i) of output channel i (see calcTheta),
therefore inputs and outputs must have the same order and number of channels. If the backward correction is
deactivated (bw=0) the resistance slope is set to zero for testing.
Inputs:     1) data:    all data (tr, te, vl)
            2) para:    all simulation parameters
            3) legacy:  (0): corrected behaviour, (1): MATLAB behaviour
Outputs:    1) data:    data with updated losses
            2) para:    updated parameters

V1.0: 07.11.2026, Pascal Schirmer
- Python port of updLoss.m, the structured data X2 are scaled with y2 of the same profile (F-D2)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================
from src.py.general.calcTheta import calcTheta

# ==============================================================================
# External
# ==============================================================================
import sys


#######################################################################################################################
# Main Function
#######################################################################################################################
def updLoss(data, para, legacy=0):
    ###################################################################################################################
    # MSG IN
    ###################################################################################################################
    print("START: Updating losses")

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    if para['Par']['loss']['fw'] == 1:
        for key in ('tr', 'vl'):
            d = data[key]
            if d['X'].shape[1] != d['y'].shape[1]:
                sys.exit('ERROR: Loss update requires the same number of inputs and outputs')
            d['X'] = d['X'] * calcTheta(d['y'], para, legacy)
            d['X2'] = [d['X2'][i] * calcTheta(d['y2'][i], para, legacy) for i in range(0, len(d['X2']))]

    if para['Par']['loss']['bw'] == 0:
        para['Par']['loss']['Rslope'] = 0

    ###################################################################################################################
    # MSG Out
    ###################################################################################################################
    print("DONE: Updating losses")

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return [data, para]


