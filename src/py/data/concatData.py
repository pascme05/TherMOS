"""
This function concatenates multiple profiles of one split (training, testing or validation). The structured data
(one entry per profile) are kept in X2, y2, r2 and t2, the concatenated data in X, y, r and t. Additionally, the
input/output data for system identification (idData) are created: for 1D data all channels, for 2D/3D data the
input node (inpX/Y/Z) and output node (outX/Y/Z).
Inputs:     1) data:    split with lists X, y, r, t (one entry per profile)
            2) setup:   includes all simulation variables
            3) para:    all simulation parameters
Outputs:    1) out:     concatenated data

V1.0: 07.11.2026, Pascal Schirmer
- Python port of concatData.m, idData is a dictionary {'u': [...], 'y': [...], 'Ts': Ts} (one entry per profile)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================
from src.py.general.findNode import findNode

# ==============================================================================
# External
# ==============================================================================
import numpy as np


#######################################################################################################################
# Additional Functions
#######################################################################################################################
def calcIdData(X2, y2, Ts, Data, dim, para, legacy):
    # 1D data
    if dim == 1:
        return {'u': [np.atleast_2d(x.T).T for x in X2], 'y': [np.atleast_2d(y.T).T for y in y2], 'Ts': Ts}

    # 2D/3D data
    gen = para['Dat']['gen']
    if dim == 2:
        idInp = findNode(Data['geo'], [gen['inpX'], gen['inpY']], legacy)
        idOut = findNode(Data['geo'], [gen['outX'], gen['outY']], legacy)
    else:
        idInp = findNode(Data['geo'], [gen['inpX'], gen['inpY'], gen['inpZ']], legacy)
        idOut = findNode(Data['geo'], [gen['outX'], gen['outY'], gen['outZ']], legacy)

    return {'u': [x[:, [idInp]] for x in X2], 'y': [y[:, [idOut]] for y in y2], 'Ts': Ts}


#######################################################################################################################
# Main Function
#######################################################################################################################
def concatData(data, setup, para):
    ###################################################################################################################
    # MSG IN
    ###################################################################################################################
    print("INFO: Concatenating data")

    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    # ==============================================================================
    # Parameters
    # ==============================================================================
    N = len(data['y'])
    Ts = data['Ts']

    # ==============================================================================
    # Variables
    # ==============================================================================
    out = {k: v for k, v in data.items() if k not in ('X', 'y', 'r', 't')}

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    # ==============================================================================
    # Structured Data
    # ==============================================================================
    out['X2'] = data['X']
    out['y2'] = data['y']
    out['r2'] = data['r']
    out['t2'] = data['t']

    # ==============================================================================
    # Concatenated Data
    # ==============================================================================
    out['X'] = np.concatenate(data['X'], axis=0)
    out['y'] = np.concatenate(data['y'], axis=0)
    out['r'] = np.concatenate(data['r'], axis=0)
    out['Nt'] = [len(t) for t in data['t']]
    out['id'] = np.concatenate([(i + 1) * np.ones(out['Nt'][i], dtype=int) for i in range(0, N)])
    out['t'] = np.arange(sum(out['Nt'])) * Ts

    ###################################################################################################################
    # Post-Processing
    ###################################################################################################################
    out['idData'] = calcIdData(out['X2'], out['y2'], Ts, out.get('Data'), setup['datDim'], para, setup['legacy'])

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return out


