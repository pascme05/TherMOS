"""
This function adds pad samples in front of every profile (pre-padding). The input is padded with zeros, the output,
reference and offset are padded with their first value per channel, so that no artificial step is created.
Inputs:     1) data:    data of one split
            2) para:    all simulation parameters
            3) legacy:  (0): corrected behaviour, (1): MATLAB behaviour
Outputs:    1) data:    padded data

V1.0: 07.11.2026, Pascal Schirmer
- Python port of padData.m
- Pad values are taken per channel (legacy: first element of channel 1 for all channels, output padded with zero,
  F-D7), the profile lengths Nt are updated
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
import numpy as np


#######################################################################################################################
# Additional Functions
#######################################################################################################################
def _pad(x, pad, mode):
    x = np.asarray(x)
    if mode == 'zero':
        head = np.zeros((pad,) + x.shape[1:])
    elif mode == 'first':
        head = np.repeat(x[0:1], pad, axis=0)
    else:
        head = np.ones((pad,) + x.shape[1:]) * x.ravel()[0]
    return np.concatenate([head, x], axis=0)


#######################################################################################################################
# Main Function
#######################################################################################################################
def padData(data, para, legacy=0):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    pad = int(para['Exp']['gen']['pad'])
    Ts = data['Ts']
    data = dict(data)

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    if pad > 0:
        print('INFO: Adding padding samples %d' % pad)
        yMode = 'zero' if legacy == 1 else 'first'
        rMode = 'scalar' if legacy == 1 else 'first'

        # ==============================================================================
        # Structured
        # ==============================================================================
        data['X2'] = [_pad(x, pad, 'zero') for x in data['X2']]
        data['y2'] = [_pad(y, pad, yMode) for y in data['y2']]
        data['r2'] = [_pad(r, pad, rMode) for r in data['r2']]
        data['off2'] = [_pad(o, pad, rMode) for o in data['off2']]
        data['t2'] = [np.arange(len(t) + pad) * Ts for t in data['t2']]
        data['Nt'] = [n + pad for n in data['Nt']]

        # ==============================================================================
        # Unstructured
        # ==============================================================================
        if legacy == 1:
            data['X'] = _pad(data['X'], pad, 'zero')
            data['y'] = _pad(data['y'], pad, 'zero')
            data['r'] = _pad(data['r'], pad, 'scalar')
            data['off'] = _pad(data['off'], pad, 'scalar')
            data['id'] = _pad(data['id'], pad, 'first')
        else:
            data['X'] = np.concatenate(data['X2'], axis=0)
            data['y'] = np.concatenate(data['y2'], axis=0)
            data['r'] = np.concatenate(data['r2'], axis=0)
            data['off'] = np.concatenate(data['off2'], axis=0)
            data['id'] = np.concatenate([(i + 1) * np.ones(n, dtype=int) for i, n in enumerate(data['Nt'])])

    ###################################################################################################################
    # Post-Processing
    ###################################################################################################################
    data['t'] = np.arange(len(data['y'])) * Ts

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return data


