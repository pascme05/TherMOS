"""
This function removes the offset from the output data. The method is selected with para['Exp']['gen']['init']:
(1) output unchanged, (2) initial value of every profile is subtracted, (3) reference signal is subtracted.
The offsets are stored in 'off' (concatenated) and 'off2' (per profile) and are added back with offAdd.
Inputs:     1) data:    data of one split
            2) para:    all simulation parameters
            3) legacy:  (0): corrected behaviour, (1): MATLAB behaviour
Outputs:    1) out:     data without offset

V1.0: 07.11.2026, Pascal Schirmer
- Python port of offRemove.m
- init=2: the concatenated offset is built from the initial value of each profile, as for the structured data
  (legacy: initial value of the first profile for all, F-D6); an invalid option gives zero offset
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
import numpy as np


#######################################################################################################################
# Main Function
#######################################################################################################################
def offRemove(data, para, legacy=0):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    init = para['Exp']['gen']['init']
    out = dict(data)
    N = len(data['y2'])

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    # ==============================================================================
    # No Removal
    # ==============================================================================
    if init == 1:
        off2 = [np.zeros_like(y) for y in data['y2']]
        off = np.zeros_like(data['y'])
        print("INFO: Output data unchanged")

    # ==============================================================================
    # Init to Zero
    # ==============================================================================
    elif init == 2:
        off2 = [np.ones_like(y) * y[0] for y in data['y2']]
        if legacy == 1:
            off = np.ones_like(data['y']) * data['y'][0]
        else:
            off = np.concatenate(off2, axis=0)
        print("INFO: Initial value of zero is used")

    # ==============================================================================
    # Remove Reference
    # ==============================================================================
    elif init == 3:
        off2 = [np.array(r, copy=True) for r in data['r2']]
        off = np.array(data['r'], copy=True)
        print("INFO: Reference signal is subtracted")

    # ==============================================================================
    # Invalid
    # ==============================================================================
    else:
        off2 = [np.zeros_like(y) for y in data['y2']]
        off = np.zeros_like(data['y'])
        print("WARN: Invalid input for offset removal, output data unchanged")

    ###################################################################################################################
    # Post-Processing
    ###################################################################################################################
    out['y'] = data['y'] - off
    out['y2'] = [data['y2'][i] - off2[i] for i in range(0, N)]
    out['off'] = off
    out['off2'] = off2

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return out


