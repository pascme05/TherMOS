"""
This function estimates the input matrix B (and optionally the initial states x0 of every experiment) of a discrete
state-space system with given A and C (D = 0) by linear least squares. The output is linear in B and x0:

    y(k) = C·A^k·x0 + Σ_{τ<k} C·A^(k-1-τ)·B·u(τ)

Every element of B and x0 is excited once (simulation with a unit matrix) and the resulting output sequences are the
columns of the regression matrix.
Inputs:     1) A:       system matrix (n x n)
            2) C:       output matrix (p x n)
            3) uList:   list of inputs (Nt_i x m), one per experiment
            4) yList:   list of outputs (Nt_i x p), one per experiment
            5) estX0:   (0) x0 = 0, (1) x0 estimated per experiment
Outputs:    1) B:       input matrix (n x m)
            2) x0:      list of initial states (n), one per experiment
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================
from src.py.numeric.simSS import simSS

# ==============================================================================
# External
# ==============================================================================
import numpy as np


#######################################################################################################################
# Main Function
#######################################################################################################################
def fitBx0(A, C, uList, yList, estX0=0):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    n = A.shape[0]
    m = uList[0].shape[1]
    E = len(uList)
    nB = n * m
    nX = n * E if estX0 else 0
    rows, rhs = [], []

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    for e in range(0, E):
        u, y = uList[e], yList[e]
        Nt, p = y.shape
        Phi = np.zeros((Nt * p, nB + nX))

        # B columns
        for j in range(0, nB):
            Bj = np.zeros(nB)
            Bj[j] = 1
            Phi[:, j] = simSS(A, Bj.reshape(n, m, order='F'), C, None, u)[0].ravel()

        # x0 columns
        if estX0:
            for j in range(0, n):
                x0 = np.zeros(n)
                x0[j] = 1
                Phi[:, nB + e * n + j] = simSS(A, np.zeros((n, m)), C, None, np.zeros_like(u), x0)[0].ravel()

        rows.append(Phi)
        rhs.append(y.ravel())

    theta = np.linalg.lstsq(np.vstack(rows), np.concatenate(rhs), rcond=None)[0]

    ###################################################################################################################
    # Post-Processing
    ###################################################################################################################
    B = theta[0:nB].reshape(n, m, order='F')
    x0 = [theta[nB + e * n:nB + (e + 1) * n] if estX0 else np.zeros(n) for e in range(0, E)]

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return [B, x0]


