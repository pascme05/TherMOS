"""
This function returns the N-point Gauss-Legendre quadrature nodes and weights mapped to the interval [a, b]:

    ∫ f(x) dx ≈ Σ w_i · f(x_i)

Inputs:     1) N:       number of nodes
            2) a:       lower bound of the interval
            3) b:       upper bound of the interval
Outputs:    1) x:       nodes (N)
            2) w:       weights (N)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
import numpy as np


#######################################################################################################################
# Main Function
#######################################################################################################################
def gaussLegendre(N, a=-1.0, b=1.0):
    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    x, w = np.polynomial.legendre.leggauss(int(N))
    x = 0.5 * (b - a) * x + 0.5 * (b + a)
    w = 0.5 * (b - a) * w

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return [x, w]


