"""
This function calculates the sparse matrix of the multilinear (bilinear in 2D, trilinear in 3D) interpolation from a
regular grid to arbitrary query points, i.e. v_q = R · v_grid.ravel() (C order). It corresponds to interp2/interp3
with the 'linear' method; query points outside the grid are clipped to the grid.
Inputs:     1) axes:    list of grid vectors in the order of the array dimensions, e.g. [y, x] or [y, x, z] (m)
            2) qpts:    query points (Nq x d) in the same order as axes (m)
Outputs:    1) R:       sparse interpolation matrix (Nq x Π len(axes))
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
import itertools
import numpy as np
from scipy.sparse import csr_matrix


#######################################################################################################################
# Main Function
#######################################################################################################################
def calcMultilinMat(axes, qpts):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    qpts = np.atleast_2d(np.asarray(qpts, dtype=float))
    Nq, d = qpts.shape
    shape = [len(a) for a in axes]
    idx, frac = [], []

    ###################################################################################################################
    # Pre-Processing
    ###################################################################################################################
    for k in range(0, d):
        a = np.asarray(axes[k], dtype=float)
        q = np.clip(qpts[:, k], a[0], a[-1])
        i = np.clip(np.searchsorted(a, q, side='right') - 1, 0, max(len(a) - 2, 0))
        if len(a) > 1:
            f = (q - a[i]) / (a[i + 1] - a[i])
        else:
            f = np.zeros(Nq)
        idx.append(i)
        frac.append(f)

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    rows, cols, vals = [], [], []
    for corner in itertools.product([0, 1], repeat=d):
        w = np.ones(Nq)
        lin = np.zeros(Nq, dtype=np.int64)
        for k in range(0, d):
            ik = np.minimum(idx[k] + corner[k], shape[k] - 1)
            w = w * (frac[k] if corner[k] else 1 - frac[k])
            lin = lin * shape[k] + ik
        rows.append(np.arange(Nq))
        cols.append(lin)
        vals.append(w)
    R = csr_matrix((np.concatenate(vals), (np.concatenate(rows), np.concatenate(cols))), shape=(Nq, int(np.prod(shape))))

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return R


