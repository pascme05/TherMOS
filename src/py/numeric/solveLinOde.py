"""
This function solves the linear thermal ODE of a reduced order model

    C · da/dt = -G · a + F(t),      a(0) = a0

for an input F(t) that is linear between the samples (first-order hold). The solution is exact: with A = -C⁻¹G and
B = C⁻¹ the system is discretised once with the matrix exponential of the augmented matrix

    expm([[A, B, 0], [0, 0, I/Ts], [0, 0, 0]] · Ts) = [[Φ, Γ1, Γ2], ...]
    a(k+1) = Φ·a(k) + (Γ1 - Γ2)·F(k) + Γ2·F(k+1)

and evaluated with a simple recursion. This replaces the variable step solvers (ode23s/ode45) of the MATLAB version,
which interpolate F linearly as well.
Inputs:     1) C:       capacitance matrix (K x K)
            2) G:       conductance matrix (K x K)
            3) F:       input (Nt x K)
            4) Ts:      sampling time (sec)
            5) a0:      initial value (K), zero if None
Outputs:    1) a:       solution at the sampling instants (Nt x K)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
import numpy as np
from scipy.linalg import expm


#######################################################################################################################
# Main Function
#######################################################################################################################
def solveLinOde(C, G, F, Ts, a0=None):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    C = np.atleast_2d(C)
    G = np.atleast_2d(G)
    F = np.atleast_2d(np.asarray(F, dtype=float).T).T
    K = C.shape[0]
    Nt = F.shape[0]

    ###################################################################################################################
    # Pre-Processing
    ###################################################################################################################
    # ==============================================================================
    # Continuous System
    # ==============================================================================
    if np.linalg.cond(C) > 1e12:
        print("WARN: Capacitance matrix is badly conditioned (cond=%.2e)" % np.linalg.cond(C))
    A = -np.linalg.solve(C, G)
    B = np.linalg.solve(C, np.eye(K))
    if np.max(np.real(np.linalg.eigvals(A))) > 0:
        print("WARN: Reduced order model is unstable (eigenvalue with positive real part)")

    # ==============================================================================
    # Discretisation (FOH)
    # ==============================================================================
    M = np.zeros((3 * K, 3 * K))
    M[0:K, 0:K] = A
    M[0:K, K:2 * K] = B
    M[K:2 * K, 2 * K:3 * K] = np.eye(K) / Ts
    E = expm(M * Ts)
    Phi = E[0:K, 0:K]
    G1 = E[0:K, K:2 * K]
    G2 = E[0:K, 2 * K:3 * K]

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    a = np.zeros((Nt, K))
    a[0] = 0 if a0 is None else a0
    U = F @ (G1 - G2).T
    U[0:-1] += F[1:] @ G2.T
    for i in range(0, Nt - 1):
        a[i + 1] = Phi @ a[i] + U[i]

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return a


