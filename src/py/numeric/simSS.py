"""
This function simulates a discrete-time state-space system

    x(k+1) = A·x(k) + B·u(k)
    y(k)   = C·x(k) + D·u(k)

If A is diagonalisable with a well conditioned eigenvector matrix the system is transformed to modal coordinates and
every mode is filtered with lfilter (fast, vectorised), otherwise a plain recursion is used.
Inputs:     1) A, B, C, D:  system matrices (n x n, n x m, p x n, p x m)
            2) u:           input (Nt x m)
            3) x0:          initial state (n), zero if None
Outputs:    1) y:           output (Nt x p)
            2) x:           states (Nt x n)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
import numpy as np
from scipy.signal import lfilter


#######################################################################################################################
# Main Function
#######################################################################################################################
def simSS(A, B, C, D, u, x0=None):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    A, B, C = np.atleast_2d(A), np.atleast_2d(B), np.atleast_2d(C)
    u = np.atleast_2d(np.asarray(u, dtype=float).T).T
    n = A.shape[0]
    Nt = u.shape[0]
    x0 = np.zeros(n) if x0 is None else np.asarray(x0, dtype=float).ravel()
    D = np.zeros((C.shape[0], B.shape[1])) if D is None else np.atleast_2d(D)

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    # ==============================================================================
    # Modal Simulation
    # ==============================================================================
    lam, V = np.linalg.eig(A)
    if np.linalg.cond(V) < 1e8:
        Vi = np.linalg.inv(V)
        w = u @ (Vi @ B).T
        z0 = Vi @ x0
        z = np.zeros((Nt, n), dtype=complex)
        for i in range(0, n):
            z[:, i] = lfilter([0, 1], [1, -lam[i]], w[:, i].astype(complex), zi=[z0[i]])[0]
        x = np.real(z @ V.T)

    # ==============================================================================
    # Recursion
    # ==============================================================================
    else:
        x = np.zeros((Nt, n))
        x[0] = x0
        Bu = u @ B.T
        for k in range(0, Nt - 1):
            x[k + 1] = A @ x[k] + Bu[k]

    ###################################################################################################################
    # Post-Processing
    ###################################################################################################################
    y = x @ C.T + u @ D.T

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return [y, x]


