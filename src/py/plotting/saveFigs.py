"""
This function saves all open figures as PNG files in results/<setup['name']>/ and closes them, so no figure windows
are opened. The file names are fig_<nn>_<figure title>.png, existing files with the same name are overwritten.
Inputs:     1) setup:   includes all simulation variables
            2) path:    includes all path variables
            3) dpi:     resolution of the PNG files (dots per inch)
Outputs:    1) files:   list of the saved files
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
import os
import re
import matplotlib.pyplot as plt
from os.path import join as pjoin


#######################################################################################################################
# Additional Functions
#######################################################################################################################
def _title(fig):
    t = fig._suptitle.get_text() if fig._suptitle is not None else ''
    if t == '' and len(fig.axes) > 0:
        t = fig.axes[0].get_title()
    t = re.sub(r'[^A-Za-z0-9]+', '_', t).strip('_')
    return t[0:80] if t != '' else 'figure'


#######################################################################################################################
# Main Function
#######################################################################################################################
def saveFigs(setup, path, dpi=150):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    folder = pjoin(path['results'], setup['name'])
    files = []

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    nums = plt.get_fignums()
    if len(nums) == 0:
        return files
    os.makedirs(folder, exist_ok=True)
    for i, n in enumerate(nums):
        fig = plt.figure(n)
        name = pjoin(folder, 'fig_%02d_%s.png' % (i + 1, _title(fig)))
        fig.savefig(name, dpi=dpi, bbox_inches='tight')
        files.append(name)
    plt.close('all')

    ###################################################################################################################
    # Post-Processing
    ###################################################################################################################
    print("INFO: %i figures saved to %s" % (len(files), folder))

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return files


