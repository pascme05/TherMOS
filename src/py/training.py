"""
This function trains all selected models on the training data (validation data for early stopping and
hyperparameter optimisation) and saves them to mdl/mdl_<tag>_<name>.pkl (deep learning models: .pt).
Inputs:     1) data:    training, validation and testing data
            2) setup:   includes all simulation variables
            3) para:    all simulation parameters
            4) path:    includes all path variables
Outputs:    1) mdls:    dictionary of the trained models {tag: mdl}, every model includes timeTrain (sec) and size

V1.0: 07.11.2026, Pascal Schirmer
- Python port of training.m; all selected models are trained and kept (MATLAB overwrote mdl with the last model)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================
from src.py.model.mdlReg import mdlReg

# ==============================================================================
# External
# ==============================================================================
from os.path import join as pjoin
import os
import pickle
import time
import torch


#######################################################################################################################
# Main Function
#######################################################################################################################
def training(data, setup, para, path):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    mdls = {}
    os.makedirs(path['mdl'], exist_ok=True)

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    for m in mdlReg(setup):
        # ==============================================================================
        # Fitting
        # ==============================================================================
        tStart = time.time()
        mdl = m['fit'](data['tr'], data['vl'], para)
        mdl['timeTrain'] = time.time() - tStart
        mdl['size'] = m['size'](mdl)
        print("INFO: %s trained in %.2f sec (%d parameters)" % (m['name'], mdl['timeTrain'], mdl['size']))

        # ==============================================================================
        # Saving
        # ==============================================================================
        name = pjoin(path['mdl'], 'mdl_' + m['tag'] + '_' + setup['name'])
        if m['tag'] in ('dl', 'pi'):
            torch.save(mdl, name + '.pt')
        else:
            with open(name + '.pkl', 'wb') as f:
                pickle.dump(mdl, f)
        mdls[m['tag']] = mdl

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return mdls


