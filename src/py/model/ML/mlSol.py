"""
This function predicts the temperature of the first node with the fitted machine learning model. For constant
losses all samples are predicted at once; for temperature dependent losses (Rohm ≠ 0) the losses are scaled sample
by sample with θ(T(k-1) + Toff(k-1)) (see calcTheta) before the prediction of T(k).
Inputs:     1) mdl:     fitted model
            2) data:    testing data
            3) para:    all simulation parameters
            4) setup:   includes all simulation variables
            5) legacy:  (0): corrected behaviour, (1): MATLAB behaviour
Outputs:    1) out:     prediction

V1.0: 07.11.2026, Pascal Schirmer
- Python port of mlSol.m; the first sample is predicted as well (MATLAB left it zero, F-L3) and the features are
  calculated as in training
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================
from src.py.general.calcFeat import calcFeat
from src.py.general.calcTheta import calcTheta

# ==============================================================================
# External
# ==============================================================================
import numpy as np


#######################################################################################################################
# Main Function
#######################################################################################################################
def mlSol(mdl, data, para, setup, legacy=0):
    ###################################################################################################################
    # MSG IN
    ###################################################################################################################
    print("------------------------------------------")
    print("START: Solving Machine Learning model")
    print("------------------------------------------")

    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    sys = mdl['sys']
    roll = setup.get('featRoll', 0) != 0
    Pv2 = [np.array(x, dtype=float) for x in data['X2']]
    Toff2 = [np.asarray(r, dtype=float)[:, 0] for r in data['r2']]
    out = dict(data)
    y2 = []

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    for Pv, Toff in zip(Pv2, Toff2):
        # ==============================================================================
        # Constant Losses
        # ==============================================================================
        if para['Par']['loss']['Rohm'] == 0:
            X = calcFeat(Pv, setup['EWMA'], setup['EWMS'], None, legacy) if roll else Pv
            T = sys.predict(X)

        # ==============================================================================
        # Temperature Dependent Losses
        # ==============================================================================
        else:
            T = np.zeros(len(Pv))
            start = 1 if legacy == 1 else 0
            for i in range(start, len(Pv)):
                if i > 0:
                    Pv[i] = Pv[i] * calcTheta(T[i - 1] + Toff[i - 1], para, legacy)
                X = calcFeat(Pv[0:i + 1], setup['EWMA'], setup['EWMS'], None, legacy)[-1:] if roll else Pv[i:i + 1]
                T[i] = sys.predict(X)[0]
        y2.append(T[:, None])

    ###################################################################################################################
    # Post-Processing
    ###################################################################################################################
    out['y'] = np.concatenate(y2)
    out['X'] = np.concatenate(Pv2)

    ###################################################################################################################
    # MSG Out
    ###################################################################################################################
    print("DONE: Solving Machine Learning model")

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return out


