"""
This function predicts the testing data with the Krylov model (KR mode). The block Krylov basis is rebuilt from the
finite-volume operator of the testing board and the heat sources of the testing profiles (calcKrylov): a new layout,
material or cooling is covered exactly, but only because its operator is known. The time for the factorisation and
the reduction is reported separately from the simulation (odeTime = both).

    θ(t) ≈ V_r·x(t),    C_r·dx/dt = −G_r·x + B_r·p(t),     T = T_ref + θ

Inputs:     1) mdl:     model of krFit (settings q, hold, srcTol)
            2) data:    testing data (X2: heat generation (W/m³), Data: geometry and operator)
            3) para:    all simulation parameters
            4) legacy:  not used
Outputs:    1) out:     prediction (y: temperatures at the nodes, theta_hat: reduced states, odeTime, tRed, r)

V1.0: 21.11.2026, Pascal Schirmer
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================
from src.py.model.KR.calcKrylov import simulate
from src.py.model.KR.krFit import reduce
from src.py.model.PF.pfData import offset

# ==============================================================================
# External
# ==============================================================================
import time
import numpy as np


#######################################################################################################################
# Main Function
#######################################################################################################################
def krSol(mdl, data, para, legacy=0):
    ###################################################################################################################
    # MSG IN
    ###################################################################################################################
    print("------------------------------------------")
    print("START: Solving Krylov Model")
    print("------------------------------------------")

    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    init = int(para['Exp']['gen'].get('init', 1) or 1)
    Ts = float(np.ravel(data['Ts'])[0])
    out = dict(data)
    off = offset(data, init)

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    tStart = time.time()
    [_, p, R] = reduce(data, mdl['q'], mdl['srcTol'])
    print("INFO: Krylov basis of the testing board: r = %d states, reduction %.3f s" % (R['r'], R['tRed']))
    y2, x2 = [], []
    for pk, o in zip(p, off):
        x = simulate(R, pk, Ts, mdl['hold'])
        y2.append(x @ R['V'].T + o)
        x2.append(x)

    ###################################################################################################################
    # Post-Processing
    ###################################################################################################################
    out['odeTime'] = time.time() - tStart
    out['tRed'] = R['tRed']
    out['r'] = R['r']
    out['y'] = np.concatenate(y2)
    out['theta_hat'] = np.concatenate(x2)

    ###################################################################################################################
    # MSG Out
    ###################################################################################################################
    print("DONE: Solving Krylov Model")

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return out


