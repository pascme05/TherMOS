"""
This function calculates the temperature response of the identified state-space model. The initial state is zero
(para['Mdl']['ss']['init'] = 1) or estimated from the test data as in MATLAB compare (init = 2, sol = 2). If the
losses depend on temperature (Rohm ≠ 0) the losses are corrected iteratively (fixed-point iteration)

    Pv_j = Pv · θ(T_{j-1} + Toff),      j = 1, 2, ...

until the mean absolute change of the temperature is below para['Par']['gen']['err'] (K) or nSub iterations.
Inputs:     1) mdl:     identified model
            2) data:    testing data
            3) para:    all simulation parameters
            4) legacy:  (0): corrected behaviour, (1): MATLAB behaviour
Outputs:    1) out:     prediction

V1.0: 07.11.2026, Pascal Schirmer
- Python port of ssSol.m; the loss iteration of the MATLAB version did not run (syntax error) and scaled the losses
  repeatedly (F-S1), the init option was overwritten (F-S2)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================
from src.py.numeric.simSS import simSS
from src.py.numeric.fitBx0 import fitBx0
from src.py.general.calcTheta import calcTheta

# ==============================================================================
# External
# ==============================================================================
import numpy as np


#######################################################################################################################
# Main Function
#######################################################################################################################
def ssSol(mdl, data, para, legacy=0):
    ###################################################################################################################
    # MSG IN
    ###################################################################################################################
    print("------------------------------------------")
    print("START: Solving State-Space system")
    print("------------------------------------------")

    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    sys = mdl['sys']
    Pv = np.asarray(data['X'], dtype=float)
    Toff = data['r']
    maxErr = para['Par']['gen']['err']
    nSub = int(para['Mdl']['gen']['nSub'])
    scale = np.max(np.atleast_1d(para.get('Dat', {}).get('normVal', {}).get('y', {}).get('max', 1)))
    out = dict(data)

    ###################################################################################################################
    # Pre-Processing
    ###################################################################################################################
    x0 = None
    if para['Mdl']['ss']['sol'] == 2 and para['Mdl']['ss']['init'] == 2:
        x0 = fitBx0(sys['A'], sys['C'], [Pv], [np.asarray(data['y'])], 1)[1][0]
        print("INFO: Initial state estimated from the test data")

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    # ==============================================================================
    # Constant Losses
    # ==============================================================================
    T = simSS(sys['A'], sys['B'], sys['C'], sys['D'], Pv, x0)[0]

    # ==============================================================================
    # Temperature Dependent Losses
    # ==============================================================================
    if para['Par']['loss']['Rohm'] != 0:
        for it in range(0, nSub):
            PvIt = Pv * calcTheta(T + Toff, para, legacy)
            Tnew = simSS(sys['A'], sys['B'], sys['C'], sys['D'], PvIt, x0)[0]
            err = np.mean(np.abs(Tnew - T)) * scale
            T = Tnew
            if err < maxErr:
                break
        print("INFO: Loss iteration finished after %d iterations (error %.2e K)" % (it + 1, err))
        Pv = PvIt

    ###################################################################################################################
    # Post-Processing
    ###################################################################################################################
    if para['Exp']['gen']['init'] == 1:
        T = T + Toff

    out['y'] = T
    out['X'] = Pv

    ###################################################################################################################
    # MSG Out
    ###################################################################################################################
    print("DONE: Solving State-Space system")

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return out


