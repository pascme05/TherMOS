"""
This function fits the POD Galerkin model of a 2D temperature field. The POD modes φ are calculated from the training
snapshots (calcPod), the heat equation is projected onto the modes (calcPodProj) and, depending on the protocol, the
reduced matrices are calibrated with the projected training data (optPodMat):

    C·da/dt = -G·a + α∘q,       T(t) = T0 + Φ·a(t)

Protocols (para['Mdl']['pod']['protocol'], default 5): (1) unweighted sum (legacy only), (2) Gauss-Legendre
quadrature, (3) as 2 (legacy: with relative element size), (4) steady-state load correction α, (5) C and G fitted
to the data + α, (6) C and G fitted with a prior on the projected matrices + α.
Inputs:     1) data:    training data (y: temperature at the nodes (°C), X: heat generation (W/m³), Data: geometry)
            2) val:     validation data (not used)
            3) para:    all simulation parameters
            4) legacy:  (0): corrected behaviour, (1): MATLAB behaviour
Outputs:    1) mdl:     model (rPhi, sPhi, Cth, Gth, alpha, lam, E, K, Tavg, theta, protocol)

V1.0: 07.11.2026, Pascal Schirmer
- Python port of poFit.m; projection in heat capacity / conductivity form (F-P2, F-P3), energy with σ² (F-P1), modal
  coordinates and derivatives per training profile (F-P14), no boundary terms at interior Gauss nodes (F-P4)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================
from src.py.model.PO.calcPod import calcPod
from src.py.model.PO.calcPodQuad import calcPodQuad
from src.py.model.PO.calcPodProj import calcPodProj, calcPodLoad
from src.py.model.PO.optPodMat import optPodMat

# ==============================================================================
# External
# ==============================================================================
import numpy as np


#######################################################################################################################
# Main Function
#######################################################################################################################
def poFit(data, val, para, legacy=0):
    ###################################################################################################################
    # MSG IN
    ###################################################################################################################
    print("------------------------------------------")
    print("START: Fitting Proper Orthogonal Model")
    print("------------------------------------------")

    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    # ==============================================================================
    # Parameters
    # ==============================================================================
    protocol = int(para['Mdl']['pod'].get('protocol', 5) or 5)
    Ts = data['Ts']
    eps = max(para['Mdl']['gen']['eps'], 1e-10)

    # ==============================================================================
    # Variables
    # ==============================================================================
    T = np.asarray(data['y'], dtype=float)
    Q = np.asarray(data['X'], dtype=float)
    Nt = np.atleast_1d(data['Nt'])
    ids = np.repeat(np.arange(len(Nt)), Nt) if legacy == 0 else None

    ###################################################################################################################
    # Pre-Processing
    ###################################################################################################################
    # ==============================================================================
    # POD
    # ==============================================================================
    [rPhi, lam, K, E, Tavg, theta, Tc] = calcPod(T, para, legacy)
    if np.linalg.norm(np.eye(K) - rPhi.T @ rPhi) > eps:
        print("ERROR: POD modes are not orthonormal")

    # ==============================================================================
    # Quadrature
    # ==============================================================================
    quad = calcPodQuad(data['Data'], legacy, protocol)
    if legacy == 1 and protocol == 1:
        quad['W'] = np.ones_like(quad['W'])

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    # ==============================================================================
    # Projection
    # ==============================================================================
    proj = calcPodProj(quad, rPhi, legacy)
    C, G = proj['C'], proj['G']
    q = calcPodLoad(quad, proj['phiQ'], Q, legacy)

    # ==============================================================================
    # Modal Coordinates
    # ==============================================================================
    if legacy == 1:
        a = theta - theta[0]
    else:
        a = np.zeros_like(theta)
        for i in range(0, len(Nt)):
            m = ids == i
            a[m] = (T[m] - T[m][0]) @ rPhi

    # ==============================================================================
    # Calibration
    # ==============================================================================
    [C, G, alpha] = optPodMat(a, q, Ts, C, G, protocol, ids)

    ###################################################################################################################
    # Post-Processing
    ###################################################################################################################
    mdl = {'rPhi': rPhi, 'sPhi': proj['sPhi'], 'theta': theta, 'Gth': G, 'Cth': C, 'lam': lam, 'E': E, 'K': K,
           'Tavg': Tavg, 'alpha': alpha, 'protocol': protocol, 'matCond': np.linalg.cond(C) + np.linalg.cond(G)}

    ###################################################################################################################
    # MSG Out
    ###################################################################################################################
    print("DONE: Fitting Proper Orthogonal Model")

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return mdl


