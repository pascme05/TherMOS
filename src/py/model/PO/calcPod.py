"""
This function calculates the proper orthogonal decomposition (POD) of the temperature snapshots T (Nt x N). After
mean centering the singular value decomposition T/sqrt(Nt-1) = U·S·Φᵀ gives the orthonormal spatial modes Φ (columns)
and the singular values σ. The captured energy of the first K modes is

    E(K) = Σ_{i≤K} σ_i² / Σ_i σ_i²

The number of modes is para['Mdl']['pod']['K'] (sel = 1, 3) or the smallest K with E(K) ≥ Emax, K ≤ Kmax (sel = 2).
The temporal modes are θ(t) = Φᵀ·(T(t) - T̄).
Inputs:     1) T:       temperature snapshots (Nt x N) (°C)
            2) para:    all simulation parameters
            3) legacy:  (0): corrected behaviour, (1): MATLAB behaviour (energy with σ instead of σ², one mode more)
Outputs:    1) rPhi:    spatial modes (N x K)
            2) lam:     singular values σ (all)
            3) K:       number of modes
            4) E:       captured energy (p.u.)
            5) Tavg:    temporal mean of the snapshots (N) (°C)
            6) theta:   temporal modes (Nt x K)
            7) Tc:      mean centred snapshots (Nt x N)

V1.0: 07.11.2026, Pascal Schirmer
- Python port of the POD part of poFit.m/psFit.m/ps3Fit.m (economy SVD only, energy with σ², F-P1, F-P10)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
import numpy as np


#######################################################################################################################
# Main Function
#######################################################################################################################
def calcPod(T, para, legacy=0):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    Nt = T.shape[0]
    Kmax = int(para['Mdl']['gen']['Kmax'])
    Emax = para['Mdl']['gen']['Emax']
    pod = para['Mdl']['pod']

    ###################################################################################################################
    # Pre-Processing
    ###################################################################################################################
    Tavg = np.mean(T, axis=0)
    Tc = T - Tavg

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    # ==============================================================================
    # Decomposition
    # ==============================================================================
    _, lam, Vt = np.linalg.svd(Tc / np.sqrt(Nt - 1), full_matrices=False)
    en = np.abs(lam) if legacy == 1 else lam ** 2
    Ecum = np.cumsum(en) / np.sum(en)

    # ==============================================================================
    # Mode Selection
    # ==============================================================================
    if pod['sel'] == 2:
        if legacy == 1:
            n, E = 1, 0
            while E < Emax and n < Kmax:
                E = Ecum[n - 1]
                n = n + 1
            K = n
        else:
            K = int(min(np.searchsorted(Ecum, Emax) + 1, Kmax))
    else:
        K = int(pod['K'])
    K = min(K, len(lam))
    E = float(Ecum[K - 1])

    # ==============================================================================
    # Modes
    # ==============================================================================
    rPhi = Vt[0:K].T
    theta = Tc @ rPhi

    ###################################################################################################################
    # Post-Processing
    ###################################################################################################################
    print('INFO: Number of used eigenvalues (model order) K: %i' % K)
    print('INFO: Cumulative correlation energy Em: %f' % (E * 100))

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return [rPhi, lam, K, E, Tavg, theta, Tc]


