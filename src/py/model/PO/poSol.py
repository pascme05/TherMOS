"""
This function solves the POD Galerkin model for the testing data

    C·da/dt = -G·a + α∘q(t),    a(0) = 0,       T(t) = T0 + Φ·a(t)

with T0 the measured initial temperature field and q the projected heat generation (linear between the samples).
The ODE is solved exactly with the matrix exponential (solveLinOde), separately for every testing profile.
Inputs:     1) mdl:     fitted model
            2) data:    testing data
            3) para:    all simulation parameters
            4) legacy:  (0): corrected behaviour, (1): MATLAB behaviour (one run over all concatenated profiles)
Outputs:    1) out:     prediction (y: temperature at the nodes, theta_hat: modal coordinates, odeTime)

V1.0: 07.11.2026, Pascal Schirmer
- Python port of poSol.m; exact discretisation instead of ode23s with time scaling
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================
from src.py.model.PO.calcPodQuad import calcPodQuad
from src.py.model.PO.calcPodProj import calcPodLoad
from src.py.numeric.solveLinOde import solveLinOde

# ==============================================================================
# External
# ==============================================================================
import time
import numpy as np


#######################################################################################################################
# Main Function
#######################################################################################################################
def poSol(mdl, data, para, legacy=0):
    ###################################################################################################################
    # MSG IN
    ###################################################################################################################
    print("------------------------------------------")
    print("START: Solving Proper Orthogonal Model")
    print("------------------------------------------")

    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    Ts = data['Ts']
    T = np.asarray(data['y'], dtype=float)
    Q = np.asarray(data['X'], dtype=float)
    rPhi, K = mdl['rPhi'], mdl['K']
    Nt = np.atleast_1d(data['Nt']) if legacy == 0 else np.array([T.shape[0]])
    out = dict(data)

    ###################################################################################################################
    # Pre-Processing
    ###################################################################################################################
    quad = calcPodQuad(data['Data'], legacy, mdl['protocol'])
    phiQ = quad['Rq'] @ mdl['sPhi'].reshape(-1, K)
    F = calcPodLoad(quad, phiQ, Q, legacy) * mdl['alpha']

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    tStart = time.time()
    a = np.zeros((T.shape[0], K))
    Tp = np.zeros_like(T)
    i0 = 0
    for n in Nt:
        s = slice(i0, i0 + int(n))
        a[s] = solveLinOde(mdl['Cth'], mdl['Gth'], F[s], Ts)
        Tp[s] = a[s] @ rPhi.T + T[i0]
        i0 = i0 + int(n)

    ###################################################################################################################
    # Post-Processing
    ###################################################################################################################
    out['odeTime'] = time.time() - tStart
    out['y'] = Tp
    out['X'] = Q
    out['theta_hat'] = a
    out['theta'] = T @ rPhi

    ###################################################################################################################
    # MSG Out
    ###################################################################################################################
    print("DONE: Solving Proper Orthogonal Model")

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return out


