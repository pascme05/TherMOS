"""
This function predicts the temperatures with the trained deep learning model. Every testing profile is cut into
windows (dlWin, padded so that every sample is predicted once). If the losses depend on temperature (Rohm ≠ 0) the
losses are corrected iteratively (fixed-point iteration, see ssSol)

    Pv_j = Pv · θ(T_{j-1} + Toff),      j = 1, 2, ...

until the mean absolute change of the temperature is below para['Mdl']['gen']['err'] or nSub iterations.
Inputs:     1) mdl:     trained model
            2) data:    testing data
            3) para:    all simulation parameters
            4) setup:   includes all simulation variables
            5) legacy:  (0): corrected behaviour, (1): MATLAB behaviour
Outputs:    1) out:     prediction

V1.0: 07.11.2026, Pascal Schirmer
- Python port of dlSol.m; the loss iteration of MATLAB did not run (undefined variable, endless loop, F-L6)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================
from src.py.model.DL.dlWin import dlWin
from src.py.general.calcFeat import calcFeat
from src.py.general.calcTheta import calcTheta

# ==============================================================================
# External
# ==============================================================================
import numpy as np
import torch


#######################################################################################################################
# Additional Functions
#######################################################################################################################
def _predict(mdl, X2, setup, legacy):
    net, W, seq = mdl['sys'], mdl['W'], mdl['seq']
    out = []
    for X in X2:
        if setup.get('featRoll', 0) != 0:
            X = calcFeat(X, setup['EWMA'], setup['EWMS'], None, legacy)
        Xw = dlWin(X, None, W, seq, 1, 1)[0]
        with torch.no_grad():
            y = net(torch.from_numpy(Xw)).numpy()
        if seq == 0:
            y = y.reshape(-1, y.shape[-1])[0:len(X)]
        out.append(y)
    return out


#######################################################################################################################
# Main Function
#######################################################################################################################
def dlSol(mdl, data, para, setup, legacy=0):
    ###################################################################################################################
    # MSG IN
    ###################################################################################################################
    print("------------------------------------------")
    print("START: Predicting Deep Learning model")
    print("------------------------------------------")

    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    X2 = [np.asarray(x, dtype=float) for x in data['X2']]
    Toff2 = data['r2']
    errMax = para['Mdl']['gen']['err']
    nSub = int(para['Mdl']['gen']['nSub'])
    out = dict(data)

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    # ==============================================================================
    # Constant Losses
    # ==============================================================================
    y2 = _predict(mdl, X2, setup, legacy)

    # ==============================================================================
    # Temperature Dependent Losses
    # ==============================================================================
    if para['Par']['loss']['Rohm'] != 0:
        Pv2 = X2
        for it in range(0, nSub):
            Pv2 = [x * calcTheta(y[:, 0:1] + r[:, 0:1], para, legacy) for x, y, r in zip(X2, y2, Toff2)]
            yNew = _predict(mdl, Pv2, setup, legacy)
            err = np.mean(np.abs(np.concatenate(yNew) - np.concatenate(y2)))
            y2 = yNew
            if err < errMax:
                break
        X2 = Pv2
        print("INFO: Loss iteration finished after %d iterations" % (it + 1))

    ###################################################################################################################
    # Post-Processing
    ###################################################################################################################
    out['y'] = np.concatenate(y2)
    out['X'] = np.concatenate(X2)

    ###################################################################################################################
    # MSG Out
    ###################################################################################################################
    print("DONE: Predicting Deep Learning model")

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return out


