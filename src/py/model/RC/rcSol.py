"""
This function calculates the temperature response of the fitted 1D Foster network (first input/output channel) with
the trapezoidal rule (see rcSim). If the losses depend on temperature (Rohm ≠ 0) they are scaled in every step with
θ(T(i-1) + Toff(i-1)) (see calcTheta), with Toff the reference temperature.
Inputs:     1) mdl:     fitted model (Rth, tau)
            2) data:    testing data
            3) para:    all simulation parameters
            4) legacy:  (0): corrected behaviour, (1): MATLAB behaviour
Outputs:    1) out:     prediction (y: temperature, yN: temperature of every RC pair, X: losses used)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================
from src.py.model.RC.rcSim import rcSim
from src.py.general.calcTheta import calcTheta

# ==============================================================================
# External
# ==============================================================================
import numpy as np


#######################################################################################################################
# Main Function
#######################################################################################################################
def rcSol(mdl, data, para, legacy=0):
    ###################################################################################################################
    # MSG IN
    ###################################################################################################################
    print("------------------------------------------")
    print("START: Solving Foster Network")
    print("------------------------------------------")

    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    Ts = data['Ts']
    Rth, tau, K = mdl['Rth'], mdl['tau'], mdl['K']
    Pv = np.array(data['X'][:, 0], dtype=float)
    Toff = data['r'][:, 0]
    Nt = len(Pv)
    out = dict(data)

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    # ==============================================================================
    # Constant Losses
    # ==============================================================================
    if para['Par']['loss']['Rohm'] == 0:
        [Tj, Tn] = rcSim(Rth, tau, Pv, Ts)

    # ==============================================================================
    # Temperature Dependent Losses
    # ==============================================================================
    else:
        a = (2 * tau - Ts) / (2 * tau + Ts)
        b = Rth * Ts / (2 * tau + Ts)
        Tn = np.zeros((Nt, K))
        Tj = np.zeros(Nt)
        for i in range(1, Nt):
            Pv[i] = Pv[i] * calcTheta(Tj[i - 1] + Toff[i - 1], para, legacy)
            Tn[i] = a * Tn[i - 1] + b * (Pv[i] + Pv[i - 1])
            Tj[i] = np.sum(Tn[i])

    ###################################################################################################################
    # Post-Processing
    ###################################################################################################################
    if para['Exp']['gen']['init'] == 1:
        Tj = Tj + Toff

    out['y'] = Tj[:, None]
    out['yN'] = Tn
    out['X'] = Pv[:, None]

    ###################################################################################################################
    # MSG Out
    ###################################################################################################################
    print("DONE: Solving Foster Network")

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return out


