"""
This function simulates a 1D Foster network with K RC pairs for a given loss profile using the trapezoidal rule
(Tustin) for every RC pair:

    T_k(i) = (2τ_k - Ts)/(2τ_k + Ts) · T_k(i-1) + Rth_k·Ts/(2τ_k + Ts) · (Pv(i) + Pv(i-1))
    T(i)   = Σ_k T_k(i)

with τ_k = Rth_k·Cth_k the time constant (sec), Rth_k the thermal resistance (K/W) and Ts the sampling time (sec).
Inputs:     1) Rth:     thermal resistances (K) (K/W)
            2) tau:     time constants (K) (sec)
            3) Pv:      power losses (Nt) (W)
            4) Ts:      sampling time (sec)
Outputs:    1) T:       temperature rise (Nt) (K)
            2) Tn:      temperature rise of every RC pair (Nt x K) (K)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
import numpy as np
from scipy.signal import lfilter


#######################################################################################################################
# Main Function
#######################################################################################################################
def rcSim(Rth, tau, Pv, Ts):
    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    Pv = np.asarray(Pv, dtype=float).ravel()
    Rth = np.atleast_1d(Rth)
    tau = np.atleast_1d(tau)
    Tn = np.zeros((len(Pv), len(Rth)))

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    for k in range(0, len(Rth)):
        a = (2 * tau[k] - Ts) / (2 * tau[k] + Ts)
        b = Rth[k] * Ts / (2 * tau[k] + Ts)
        # recursion with T_k(0) = 0, i.e. the response to Pv(0) at i=0 is removed
        Tn[:, k] = lfilter([b, b], [1, -a], Pv) - b * Pv[0] * a ** np.arange(len(Pv))

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return [Tn.sum(axis=1), Tn]


