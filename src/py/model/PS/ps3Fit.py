"""
This function fits the POD state-space model of a 3D temperature field. The implementation of psFit is dimension
independent (2D/3D is detected from the geometry); in the legacy mode the element size threshold is 0.01 (ps3Fit.m).
Inputs:     1) data:    training data (3D)
            2) val:     validation data (not used)
            3) para:    all simulation parameters
            4) legacy:  (0): corrected behaviour, (1): MATLAB behaviour
Outputs:    1) mdl:     model (see psFit)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================
from src.py.model.PS.psFit import psFit

# ==============================================================================
# External
# ==============================================================================


#######################################################################################################################
# Main Function
#######################################################################################################################
def ps3Fit(data, val, para, legacy=0):
    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    mdl = psFit(data, val, para, legacy, 0.01)

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return mdl


