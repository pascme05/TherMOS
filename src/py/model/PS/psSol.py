"""
This function solves the POD state-space model for the testing data (zero initial state, see psFit)

    x(k+1) = A·x(k) + B·q(k),       a(k) = C·x(k),      T(k) = T0 + Φ·a(k)

separately for every testing profile.
Inputs:     1) mdl:     fitted model
            2) data:    testing data
            3) para:    all simulation parameters
            4) legacy:  (0): corrected behaviour, (1): MATLAB behaviour (one run over all concatenated profiles)
Outputs:    1) out:     prediction (y: temperature at the nodes, theta_hat: modal coordinates, odeTime)

V1.0: 07.11.2026, Pascal Schirmer
- Python port of psSol.m and ps3Sol.m; the projected losses are passed as (Nt x K) input (F-P9)
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================
from src.py.model.PO.calcPodQuad import calcPodQuad
from src.py.model.PO.calcPodProj import calcPodLoad
from src.py.numeric.simSS import simSS

# ==============================================================================
# External
# ==============================================================================
import time
import numpy as np


#######################################################################################################################
# Main Function
#######################################################################################################################
def psSol(mdl, data, para, legacy=0):
    ###################################################################################################################
    # MSG IN
    ###################################################################################################################
    print("------------------------------------------")
    print("START: Solving Proper Orthogonal Model using SS")
    print("------------------------------------------")

    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    T = np.asarray(data['y'], dtype=float)
    Q = np.asarray(data['X'], dtype=float)
    rPhi, K, sys = mdl['rPhi'], mdl['K'], mdl['sys']
    Nt = np.atleast_1d(data['Nt']) if legacy == 0 else np.array([T.shape[0]])
    out = dict(data)

    ###################################################################################################################
    # Pre-Processing
    ###################################################################################################################
    quad = calcPodQuad(data['Data'], legacy, 5, mdl['th'])
    phiQ = quad['Rq'] @ mdl['sPhi'].reshape(-1, K)
    q = calcPodLoad(quad, phiQ, Q, legacy)

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    tStart = time.time()
    a = np.zeros((T.shape[0], K))
    Tp = np.zeros_like(T)
    i0 = 0
    for n in Nt:
        s = slice(i0, i0 + int(n))
        a[s] = simSS(sys['A'], sys['B'], sys['C'], sys['D'], q[s])[0]
        Tp[s] = a[s] @ rPhi.T + T[i0]
        i0 = i0 + int(n)

    ###################################################################################################################
    # Post-Processing
    ###################################################################################################################
    out['odeTime'] = time.time() - tStart
    out['y'] = Tp
    out['X'] = Q
    out['theta_hat'] = a
    out['theta'] = T @ rPhi

    ###################################################################################################################
    # MSG Out
    ###################################################################################################################
    print("DONE: Solving Proper Orthogonal Model using SS")

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return out


