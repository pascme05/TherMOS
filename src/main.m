%% Description
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% This is the main function of the TherMOS toolkit. It loads the data,
% brings the data in the correct format, trains the model, tests the model,
% evaluates the performance, and plots the results.
% -------------------------------------------------------------------------
% Inp:  1) setup:   input setup file
%       2) path:    all path variable of TherMOS
% Out:  1) None

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Function
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
function [] = main(setup, path)
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %% Message Input
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    disp('%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%')
    disp('%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%')
    disp('----Thermal Model Order Reduction and Simulation (TherMOS)-----')
    disp('%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%')
    disp('%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%')
    disp('===================================================')
    disp('Author:             Dr. Pascal A. Schirmer')
    disp('Version:            V.0.1')
    disp('Date:               13.08.2024')
    disp('Copyright:          Pascal Schirmer')
    disp('===================================================')
    fprintf('Setup File:\t\t\t%s\n', setup.name);
    fprintf('Config File:\t\t%s\n', setup.config);
    disp('===================================================')
    fprintf('Train Data:\t\t\t%s\n', setup.trFile);
    fprintf('Test Data:\t\t\t%s\n', setup.teFile);
    fprintf('Val Data:\t\t\t%s\n', setup.vlFile);
    disp('===================================================')
    fprintf('Plot Output:\t\t%d\n', setup.plotOut);
    fprintf('Plot Model:\t\t\t%d\n', setup.plotMdl);
    fprintf('Saving Output:\t\t%d\n', setup.save);
    disp('===================================================')
    fprintf('Training:\t\t\t%d\n', setup.train);
    fprintf('Testing:\t\t\t%d\n', setup.test);
    disp('===================================================')
    fprintf('RC-Mdl:\t\t\t\t%d\n', setup.selRC);
    fprintf('SS-Mdl:\t\t\t\t%d\n', setup.selSS);
    fprintf('SF-Mdl:\t\t\t\t%d\n', setup.selSF);
    fprintf('PO-Mdl:\t\t\t\t%d\n', setup.selPO);
    disp('===================================================')
    disp('%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%')
    disp('%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%')

    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %% Data
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %===================================================
    % Msg
    %===================================================
    disp('===================================================')
    disp('Loading Para and Data')
    disp('===================================================')
   
    %===================================================
    % Loading Para
    %===================================================
    para = loadPara(setup.config, path);

    %===================================================
    % Loading Data
    %===================================================
    data = loadData(para, setup);

    %===================================================
    % Sanity Check Data (tbi)
    %===================================================
    % Remove NaNs and Infs
    % Calc Storage limits

    
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %% Pre-Processing
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %===================================================
    % Msg
    %===================================================
    disp('===================================================')
    disp('Pre-Processing')
    disp('===================================================')
    
    %===================================================
    % Update Losses
    %===================================================
    %----------------------------------------
    % Msg
    %----------------------------------------
    disp("----------------------------------------");
    disp("Update Losses")
    disp("----------------------------------------");

    %----------------------------------------
    % Calc
    %----------------------------------------
    [data, para] = updLoss(data, para);
    fprintf('\n');
    
    %===================================================
    % Offset Removal
    %===================================================
    %----------------------------------------
    % Msg
    %----------------------------------------
    disp("----------------------------------------");
    disp("Offset Removal")
    disp("----------------------------------------");

    %----------------------------------------
    % Calc
    %----------------------------------------
    data.tr = offRemove(data.tr, para);
    data.te = offRemove(data.te, para);
    data.vl = offRemove(data.vl, para);
    fprintf('\n');

    %===================================================
    % Normalisation
    %===================================================
    %----------------------------------------
    % Msg
    %----------------------------------------
    disp("----------------------------------------");
    disp("Normalisation")
    disp("----------------------------------------");

    %----------------------------------------
    % Calc
    %----------------------------------------
    [data.tr, para] = normData(data.tr, para, 1);
    [data.te, ~] = normData(data.te, para, 2);
    [data.vl, ~] = normData(data.vl, para, 2);
    fprintf('\n');

    %===================================================
    % Pre-Padding
    %===================================================
    %----------------------------------------
    % Msg
    %----------------------------------------
    disp("----------------------------------------");
    disp("Pre-Padding")
    disp("----------------------------------------");

    %----------------------------------------
    % Calc
    %----------------------------------------
    data.tr = padData(data.tr, para);
    % data.te = padData(data.te, para);
    data.vl = padData(data.vl, para);
    fprintf('\n');

    %===================================================
    % Adapt data dimension
    %===================================================
    %----------------------------------------
    % Msg
    %----------------------------------------
    disp("----------------------------------------");
    disp("Adapt Dimension")
    disp("----------------------------------------");

    %----------------------------------------
    % Calc
    %----------------------------------------
    data = dimData(data, setup, para);
    fprintf('\n');


    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %% Calculation
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %===================================================
    % Msg
    %===================================================
    disp('===================================================')
    disp('Calculation')
    disp('===================================================')

    %===================================================
    % Training
    %===================================================
    if setup.train == 1
        %----------------------------------------
        % Msg
        %----------------------------------------
        disp("----------------------------------------");
        disp("Training Model")
        disp("----------------------------------------");
        
        %----------------------------------------
        % Training
        %----------------------------------------
        mdl = training(data, setup, para, path);
        fprintf('\n');
    else
        %----------------------------------------
        % Empty Model
        %----------------------------------------
        mdl = [];
    end
    
    %===================================================
    % Testing
    %===================================================
    %----------------------------------------
    % Msg
    %----------------------------------------
    disp("----------------------------------------");
    disp("Testing Model")
    disp("----------------------------------------");

    %----------------------------------------
    % Testing
    %----------------------------------------
    [data.pr, data.te, mdl] = testing(mdl, data, setup, para, path);
    fprintf('\n');
    

    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %% Post-Processing
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %===================================================
    % Msg
    %===================================================
    disp('===================================================')
    disp('Post-Processing')
    disp('===================================================')

    %===================================================
    % De-Normalisation
    %===================================================
    %----------------------------------------
    % Msg
    %----------------------------------------
    disp("----------------------------------------");
    disp("De-Normalisation")
    disp("----------------------------------------");

    %----------------------------------------
    % Calc
    %----------------------------------------
    [data.tr, ~] = normData(data.tr, para, 3);
    [data.te, ~] = normData(data.te, para, 3);
    [data.vl, ~] = normData(data.vl, para, 3);
    [data.pr, ~] = normData(data.pr, para, 3);
    fprintf('\n');

    %===================================================
    % Offset Correction
    %===================================================
    %----------------------------------------
    % Msg
    %----------------------------------------
    disp("----------------------------------------");
    disp("Offset Correction")
    disp("----------------------------------------");

    %----------------------------------------
    % Calc
    %----------------------------------------
    data.tr = offAdd(data.tr, para);
    data.te = offAdd(data.te, para);
    data.vl = offAdd(data.vl, para);
    % data.pr = offAdd(data.pr, para);
    fprintf('\n');

    %===================================================
    % Performance
    %===================================================
    %----------------------------------------
    % Msg
    %----------------------------------------
    disp("----------------------------------------");
    disp("Performance")
    disp("----------------------------------------");

    %----------------------------------------
    % Calc
    %----------------------------------------
    results = performance(data.te, data.pr, para, mdl);
    fprintf('\n');


    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %% Output
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %===================================================
    % Msg
    %===================================================
    disp('===================================================')
    disp('Output')
    disp('===================================================')
    
    %===================================================
    % Saving
    %===================================================
    %----------------------------------------
    % Msg
    %----------------------------------------
    disp("----------------------------------------");
    disp("Saving")
    disp("----------------------------------------");

    %----------------------------------------
    % Saving
    %----------------------------------------
    if setup.save == 1
        saving(data, setup, para, path);
        fprintf('\n');
    else
        disp("INFO: Saving deactivated");
        fprintf('\n');
    end

    %===================================================
    % Printing
    %===================================================
    %----------------------------------------
    % Msg
    %----------------------------------------
    disp("----------------------------------------");
    disp("Printing")
    disp("----------------------------------------");

    %----------------------------------------
    % Printing Console
    %----------------------------------------
    printConsole(data, results, setup, mdl);
    fprintf('\n');

    %===================================================
    % Plotting
    %===================================================
    %----------------------------------------
    % Msg
    %----------------------------------------
    disp("----------------------------------------");
    disp("Plotting")
    disp("----------------------------------------");

    %----------------------------------------
    % Plot Model
    %----------------------------------------
    if setup.plotMdl == 1
        plotMdl(data, mdl, setup);
    end

    %----------------------------------------
    % Plot Results
    %----------------------------------------
    if setup.plotOut ~= 0
        % 1D Output
        plotResults1D(data, results, setup);

        % 2D Output
    end
    fprintf('\n');


    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %% Message Output
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    disp('%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%')
    disp('%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%')
    disp('---------------------Simulation Completed----------------------')
    disp('%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%')
    disp('%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%')
end

