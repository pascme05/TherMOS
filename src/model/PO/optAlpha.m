function [alpha_opt, q_adj, residual] = optAlpha(u, q, dt, C, G, lam)
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %% Init
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    disp("INFO: Optimizing Alpha")

    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %% Init
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %===================================================
    % Parameter and Variables
    %===================================================
    [K, ~] = size(u);                                                       % number of POD modes
    alpha0 = ones(K, 1);
    
    %===================================================
    % Optimizer
    %===================================================
    options = optimoptions('fminunc', ...
        'Display', 'iter', ...
        'MaxIterations', 1000, ...
        'StepTolerance', 1e-15, ...
        'OptimalityTolerance', 1e-15, ...
        'FunctionTolerance', 1e-15, ...
        'Algorithm', 'quasi-newton');


    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %% Pre-processing
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    du_dt = gradient(u, dt, 2);

    
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %% Calculation
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %===================================================
    % Loss function
    %===================================================
    loss_fn = @(alpha) compute_alpha_residual(alpha, C, G, du_dt, u, q, lam);
    
    %===================================================
    % Run optimization
    %===================================================
    [alpha_opt, ~] = fminunc(loss_fn, alpha0, options);


    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %% Output
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    q_adj = alpha_opt .* q;
    q_est = C * du_dt + G * u;
    residual = q_est - q_adj;
end


%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Helper Function
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
function err = compute_alpha_residual(alpha, C, G, du_dt, u, q, lam)
    q_adj = alpha .* q; 
    q_est = C * du_dt + G * u;
    residual = (q_est - q_adj).*lam;
    err = sum(residual(:).^2);
end

