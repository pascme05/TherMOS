classdef DataLoader
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %% Properties and Variables
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    properties
        Data                                                                % Table to store the loaded data
        FileName                                                            % Name of the loaded file
        Ts {mustBeNumeric}                                                  % sampling time (sec)
    end

    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %% Methods and Functions
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    methods
        %===================================================
        % Constructor
        %===================================================
        function obj = DataLoader(Ts)
            if nargin == 1
                obj.Ts = Ts;
            end
        end

        %===================================================
        % Load xlsx Data
        %===================================================
        function r = loadXlsx(obj)
            %----------------------------------------
            % File based
            %----------------------------------------

            %----------------------------------------
            % ID based
            %----------------------------------------

            %----------------------------------------
            % Split based
            %----------------------------------------
            r = round([obj.Value],2);
        end

        %===================================================
        % Load Matlab 1D Data
        %===================================================
        function r = loadMat1D(obj,n)
            r = [obj.Value] * n;
        end

        %===================================================
        % Load Matlab 2D Data
        %===================================================
        function r = loadMat2D(obj,n)
            r = [obj.Value] * n;
        end
    end
end

