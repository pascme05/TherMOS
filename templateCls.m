classdef templateCls
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %% Properties and Variables
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    properties
        Value {mustBeNumeric}
    end

    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    %% Methods and Functions
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    methods
        %===================================================
        % Constructor
        %===================================================
        function obj = templateCls(val)
            if nargin == 1
                obj.Value = val;
            end
        end

        %===================================================
        % Function I
        %===================================================
        function r = fnc1(obj)
            r = round([obj.Value],2);
        end

        %===================================================
        % Function II
        %===================================================
